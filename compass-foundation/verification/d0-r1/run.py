def git_snapshot():
    result = {}
    for name, args in [('status', ['status', '--short', '--branch']),
                       ('diff', ['diff', '--binary']), ('diff_cached', ['diff', '--cached', '--binary']),
                       ('index', ['ls-files', '--stage']), ('head', ['rev-parse', '--verify', 'HEAD']),
                       ('branch', ['symbolic-ref', '--short', 'HEAD'])]:
        p = subprocess.run(['git', *args], cwd=ROOT, capture_output=True, timeout=GUARD)
        result[name] = dict(exit=p.returncode, stdout=raw_record(p.stdout), stderr=raw_record(p.stderr))
    return result


