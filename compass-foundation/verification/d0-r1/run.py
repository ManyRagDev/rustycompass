def files_inventory(paths):
    result = {}
    for root in paths:
        for path in ([root] if root.is_file() else sorted(root.rglob('*'))):
            if path.is_file():
                st = path.stat()
                result[str(path)] = dict(sha256=sha(path.read_bytes()), bytes=st.st_size,
                                         dev=st.st_dev, ino=st.st_ino, mode=st.st_mode,
                                         mtime_ns=st.st_mtime_ns, ctime_ns=st.st_ctime_ns)
    return result


def disk(paths):
    files = [p for root in paths for p in ([root] if root.is_file() else sorted(root.rglob('*'))) if p.is_file()]
    return dict(regular_files=len(files), logical_bytes=sum(p.stat().st_size for p in files),
                allocated_bytes=sum(p.stat().st_blocks * 512 for p in files), allocation_unit_bytes=512,
                excludes='Directory metadata, live corpus, .compass state, compiler and dependency caches')


class Lab:
    def __init__(self, binary, temporary):
        self.binary = binary
        self.temporary = temporary
        self.commands = []
        self.reports = []
        self.inputs = []
        self.samples = []
        self.loads = []

    def invoke(self, scenario, args, expected_exit=0, measured=False, repeat_of=None):
        command = [str(self.binary), *map(str, args), '--json']
        measure_path = self.temporary / (scenario + '.time')
        actual_command = (['/usr/bin/time', '-q', '-f', '%U %S %M %e %x', '-o', str(measure_path)]
                          + command) if measured else command
        start = time.perf_counter_ns()
        child = subprocess.run(actual_command, capture_output=True, timeout=GUARD, cwd=self.temporary)
        wall = time.perf_counter_ns() - start
        self.commands.append(dict(id=scenario, argv=actual_command, cwd=str(self.temporary),
                                  expected_exit=expected_exit, actual_exit=child.returncode,
                                  wall_ns_including_wrapper=wall, stdout_sha256=sha(child.stdout),
                                  stderr=raw_record(child.stderr), guard_timeout_seconds=GUARD))
        raw = child.stdout
        if repeat_of is None:
            self.reports.append(dict(id=scenario, exit=child.returncode, stdout=raw_record(raw),
                                     kind='d0' if 'd0' in args else str(args[0])))
        else:
            self.commands[-1]['report_reference'] = repeat_of
        eq(child.returncode, expected_exit, scenario + '.exit')
        value = v.strict(raw)
        eq(raw, v.canonical(value) + (b'' if 'd0' in args else b'\n'), scenario + '.canonical-bytes')
        if measured:
            time_raw = measure_path.read_bytes()
            u, s, rss, elapsed, exit_ = time_raw.decode('ascii').split()
            eq(int(exit_), 0, scenario + '.time-exit')
            require(int(rss) > 0, scenario + '.rss-positive')
            require(float(u) >= 0 and float(s) >= 0 and float(elapsed) >= 0, scenario + '.time-nonnegative')
            self.samples.append(dict(id=scenario, load=scenario.split('-')[0],
                                     report_reference=repeat_of or scenario,
                                     stdout_sha256=sha(raw), stdout_bytes=len(raw), exit=child.returncode,
                                     raw_gnu_time=raw_record(time_raw),
                                     user_cpu_seconds=u, system_cpu_seconds=s, max_rss_kib=int(rss),
                                     elapsed_seconds=elapsed, wall_ns_including_wrapper=wall))
        return value, raw

    def package(self, label, side, tree, package, snapshot_path, expected_corpus):
        obj, raw = v.snapshot(snapshot_path)
        eq(obj['producer_build'], PRODUCER, label + '.' + side + '.producer')
        eq(obj['quality'], 'complete', label + '.' + side + '.quality')
        observed = [e for e in obj['entries'] if e['state'] == 'observed']
        eq(set(v.path_bytes(e['path_key']).decode('ascii') for e in observed),
           set(expected_corpus), label + '.' + side + '.observed-paths')
        eq([v.path_bytes(e['path_key']) for e in obj['entries'] if e['state'] == 'excluded'],
           [b'.compass'], label + '.' + side + '.exclusions')
        package.mkdir()
        (package / 'objects').mkdir()
        objects = []
        for e in observed:
            name = v.path_bytes(e['path_key']).decode('ascii')
            path = tree / name
            require(path.is_file() and not path.is_symlink(), label + '.regular-source')
            data = path.read_bytes()
            eq(data, expected_corpus[name], label + '.recipe-bytes')
            eq(sha(data), e['content_sha256'], label + '.object-hash')
            eq(str(len(data)), e['size_bytes'], label + '.object-size')
            eq(e['executable'], False, label + '.executable')
            target = package / 'objects' / sha(data)
            if target.exists():
                eq(target.read_bytes(), data, label + '.duplicate-revision')
            else:
                target.write_bytes(data)
            require(target.stat().st_ino != path.stat().st_ino, label + '.no-hardlink')
            eq(sha(target.read_bytes()), e['content_sha256'], label + '.copied-hash')
            objects.append(dict(path=name, sha256=e['content_sha256'], bytes=len(data)))
        descriptor = dict(source_schema_version='1', source_contract_version='0.1.0',
                          workspace_id=obj['workspace_id'], snapshot_id=obj['snapshot_id'],
                          policy_id=obj['policy_id'], snapshot_file_sha256=sha(raw))
        source_raw = v.canonical(descriptor)
        (package / 'source.json').write_bytes(source_raw)
        v.descriptor(package, obj, raw)
        self.inputs.append(dict(id=label + '-' + side, origin='public snapshot; operator simulation copies observed bytes',
                                snapshot=raw_record(raw), descriptor=raw_record(source_raw), objects=objects))
        return obj

    def validate_report(self, label, value, raw, paths, packages, f, expected_exit=0):
        # V1 is imported by reading current files; its old live-tree integrity
        # guard is intentionally not invoked. Baseline tar integrity is separate.
        v.report(value, paths, packages, exit_code=expected_exit)
        if expected_exit != 0:
            return
        e = f[label]['expected']
        eq(value['producer_build'], PRODUCER, label + '.report-producer')
        eq(value['metric_policy_id'], POLICY, label + '.policy')
        eq(value['comparison']['counts'], e['counts'], label + '.compare-counts')
        eq(value['measurement']['status'], 'complete', label + '.complete')
        eq(value['measurement']['value'], e['value'], label + '.value')
        eq(value['measurement']['line_mass'], e['value']['denominator'], label + '.mass')
        eq(value['measurement']['reasons'], [], label + '.no-global-reasons')
        for k in ('candidates', 'resolved_text_units'):
            eq(value['scope'][k], e[k], label + '.scope.' + k)
        for k in ('unavailable_units', 'non_text_units', 'scope_transitions'):
            eq(value['scope'][k], '0', label + '.scope.' + k)
        for k, n in e['resources'].items():
            eq(value['resources'][k], n, label + '.resources.' + k)
        snapshots = [load(p) for p in paths]
        manifest_bytes = sum(p.stat().st_size for p in paths)
        descriptor_bytes = sum((p / 'source.json').stat().st_size for p in packages)
        n = sum(len(o[k]) for o in snapshots for k in ('entries', 'directory_coverage', 'issues'))
        structural = 8 * (manifest_bytes + descriptor_bytes) + 4096 * n + 65536
        windows = []
        c = m = 0
        for unit in value['units']:
            name = v.path_bytes(unit['path_key']).decode('ascii')
            classification = unit['classification']
            if label == 'L':
                expected = e['calculation']
            else:
                bilateral = classification in ('unchanged', 'modified')
                n0 = 0 if classification == 'added' else 64
                nt = 0 if classification == 'removed' else 64
                lcs = 63 if classification == 'modified' else 64 if bilateral else 0
                a, r = nt - lcs, n0 - lcs
                expected = dict(n0=str(n0), nt=str(nt), l=str(lcs), a=str(a), r=str(r),
                                c=str(a + r), m=str(n0 + nt), delta=oracle.ratio(a + r, n0 + nt), zero_basis=None)
            eq(unit['calculation'], expected, label + '.unit.' + name)
            eq(unit['status'], 'available', label + '.unit-available')
            eq(unit['reasons'], [], label + '.unit-reasons')
            eq(unit['non_text'], [], label + '.unit-text')
            for side in ('baseline', 'current'):
                check = unit['checks'][side]
                if check['observation'] == 'observed':
                    eq(check['state'], 'verified', label + '.check-state')
                    eq(check['actual_revision'], check['expected_revision'], label + '.revision')
                    eq([check['hash_check'], check['size_check']], [True, True], label + '.checks')
                else:
                    eq(check['state'], 'absent', label + '.absent')
            sizes = [int(unit[k]['size_bytes']) if unit[k] else 0 for k in ('before', 'after')]
            wb = 2 * (sum(sizes) + 2) + 65536
            w = wb + 32 * (int(expected['n0']) + int(expected['nt'])) + 8 * (min(int(expected['n0']), int(expected['nt'])) + 1)
            windows.append(w)
            c += int(expected['c'])
            m += int(expected['m'])
        eq(oracle.ratio(c, m), e['value'], label + '.independent-unit-aggregate')
        eq(value['measurement']['known_subset'], dict(scope='resolved_text_units_only', value=e['value'],
           line_mass=str(m), zero_basis=None, resolved_text_units=e['resolved_text_units']), label + '.subset')
        eq(value['resources']['logical_memory_peak'], str(structural + max(windows)), label + '.ledger-S-Wb-W')
        eq(raw, v.canonical(value), label + '.JCS-no-newline')
        return dict(S=structural, manifest_bytes=manifest_bytes, descriptor_bytes=descriptor_bytes,
                    N=n, max_Wb=e['bilateral_Wb'], max_W=e['bilateral_W'],
                    logical_memory_peak=structural + max(windows), reported_resources=value['resources'])

    def load_flow(self, label, f):
        root = self.temporary / label
        root.mkdir()
        tree = root / 'live'
        tree.mkdir()
        old, new = corpus(label), corpus(label, True)
        for name, data in old.items():
            p = tree / name
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_bytes(data)
        self.invoke(label + '-init', ['init', '--root', tree])
        packages = [root / 'baseline-package', root / 'current-package']
        paths = [root / 'baseline.json', root / 'current.json']
        snapshots = []
        for i, (side, files) in enumerate(zip(('baseline', 'current'), (old, new))):
            if i:
                for name in old.keys() - new.keys():
                    (tree / name).unlink()
                for name, data in new.items():
                    if data != old.get(name):
                        p = tree / name
                        p.parent.mkdir(parents=True, exist_ok=True)
                        p.write_bytes(data)
            receipt, _ = self.invoke(label + '-snapshot-' + side, ['snapshot', '--root', tree])
            original = Path(receipt['snapshot_path'])
            require(tree in original.parents, label + '.receipt-contained')
            paths[i].write_bytes(original.read_bytes())
            snapshots.append(self.package(label, side, tree, packages[i], paths[i], files))
        eq([int(o['stats']['observed_files']) for o in snapshots], f[label]['expected']['files'], label + '.snapshot-files')
        eq([int(o['stats']['bytes_read']) for o in snapshots], f[label]['expected']['bytes'], label + '.snapshot-bytes')
        eq(snapshots[0]['workspace_id'], snapshots[1]['workspace_id'], label + '.same-workspace')
        require(packages[0].stat().st_ino != packages[1].stat().st_ino, label + '.distinct-roots')
        common = set(p.name for p in (packages[0] / 'objects').iterdir()) & set(p.name for p in (packages[1] / 'objects').iterdir())
        for name in common:
            require((packages[0] / 'objects' / name).stat().st_ino != (packages[1] / 'objects' / name).stat().st_ino, label + '.no-package-hardlinks')
        compare_args = ['compare', '--baseline', paths[0], '--current', paths[1]]
        comparison, _ = self.invoke(label + '-compare', compare_args)
        eq(comparison, v.comparison(*snapshots)[0], label + '.independent-comparison')
        eq(comparison['counts'], f[label]['expected']['counts'], label + '.literal-comparison')
        args = ['d0', '--baseline', paths[0], '--current', paths[1],
                '--baseline-source', packages[0], '--current-source', packages[1]]
        protected = files_inventory(paths + packages)
        record = dict(id=label, corpus=[corpus_digest(old), corpus_digest(new)],
                      immutable_inputs_before=protected,
                      disk=dict(manifests=disk(paths), descriptors=disk([p / 'source.json' for p in packages]),
                                objects=disk([p / 'objects' for p in packages]), packages_total=disk(packages)))
        canonical_raw = None
        for sample in range(1, 4):
            eq(files_inventory(paths + packages), protected, label + '.before-sample-immutable')
            value, raw = self.invoke(f'{label}-sample-{sample}', args, measured=True,
                                     repeat_of=None if sample == 1 else label + '-sample-1')
            ledger = self.validate_report(label, value, raw, paths, packages, f)
            eq(value['comparison'], comparison, label + '.compare-equals-d0')
            if canonical_raw is None:
                canonical_raw = raw
                record['logical_ledger'] = ledger
            eq(raw, canonical_raw, label + '.sample-repeatability')
            eq(files_inventory(paths + packages), protected, label + '.after-sample-immutable')
        record['disk']['representative_report'] = dict(logical_bytes=len(canonical_raw),
            allocated_bytes=None, note='stdout pipe; exact bytes retained base64 in reports.json, no standalone filesystem allocation')
        # Only this runner-created live tree is removed, after preserving manifest bytes.
        require(tree.parent == root and root.parent == self.temporary and tree.name == 'live', 'cleanup.ownership')
        shutil.rmtree(tree)
        require(not tree.exists(), label + '.live-removed')
        value, raw = self.invoke(label + '-without-live', args, repeat_of=label + '-sample-1')
        self.validate_report(label, value, raw, paths, packages, f)
        eq(raw, canonical_raw, label + '.without-live-identical')
        eq(files_inventory(paths + packages), protected, label + '.offline-inputs-immutable')
        record.update(live_removed=True, offline_stdout_identical=True, immutable_inputs_after=files_inventory(paths + packages))
        if label == 'L':
            record['negative_controls'] = self.negatives(args, paths, packages, f, canonical_raw)
        self.loads.append(record)
        print(label + ': public flow, three native samples, independent report checks and offline repetition PASS', flush=True)

    def negatives(self, args, paths, packages, f, valid_raw):
        results = []
        desc_path = packages[0] / 'source.json'
        desc_raw = desc_path.read_bytes()
        baseline = load(paths[0])
        entry = next(e for e in baseline['entries'] if e['state'] == 'observed')
        obj_path = packages[0] / 'objects' / entry['content_sha256']
        original = obj_path.read_bytes()
        original_hashes = {k: x['sha256'] for k, x in files_inventory(paths + packages).items()}
        for case in f['negative_controls']:
            ident = case['id']
            command = list(args)
            try:
                if ident == 'L-no-baseline-source':
                    pos = command.index('--baseline-source')
                    del command[pos:pos + 2]
                elif ident == 'L-object-missing':
                    obj_path.unlink()
                elif ident == 'L-object-tampered':
                    obj_path.write_bytes(bytes([original[0] ^ 1]) + original[1:])
                    eq(obj_path.stat().st_size, len(original), ident + '.same-size')
                else:
                    d = json.loads(desc_raw)
                    d['snapshot_file_sha256'] = '0' * 64
                    variant = v.canonical(d)
                    desc_path.write_bytes(variant)
                    self.inputs.append(dict(id=ident, variant_of='L-baseline', descriptor=raw_record(variant),
                                            intervention='Only snapshot_file_sha256 replaced by 64 zeros'))
                value, raw = self.invoke(ident, command, expected_exit=case['exit'])
                if 'code' in case:
                    eq(value, dict(error=dict(code=case['code'], message=case['code'])), ident + '.exact-envelope')
                    v.schema(value, 'error')
                    assertions = ['exit=2', 'exact incompatible_inputs envelope; message=code; no report fields']
                else:
                    actual_packages = [None, packages[1]] if ident == 'L-no-baseline-source' else packages
                    self.validate_report('L', value, raw, paths, actual_packages, f, expected_exit=1)
                    measurement = value['measurement']
                    eq(measurement['status'], 'unavailable', ident + '.unavailable')
                    eq(measurement['reasons'], ['no_text_units', 'unresolved_units'], ident + '.global-reasons')
                    for k in ('value', 'line_mass', 'zero_basis', 'known_subset'):
                        eq(measurement[k], None, ident + '.null.' + k)
                    eq(len(value['units']), 1, ident + '.one-unit')
                    unit = value['units'][0]
                    require('calculation' not in unit, ident + '.no-calculation')
                    eq(unit['reasons'], [case['reason']], ident + '.local-reason')
                    before, current = [unit['checks'][k] for k in ('baseline', 'current')]
                    eq(before['state'], case['baseline_state'], ident + '.baseline-state')
                    eq(before['reasons'], [case['reason']], ident + '.baseline-reason')
                    eq(current['state'], 'verified', ident + '.current-verified')
                    eq([current['size_check'], current['hash_check']], [True, True], ident + '.current-checks')
                    if ident == 'L-object-tampered':
                        eq([before['size_check'], before['hash_check']], [True, False], ident + '.EOF-checks')
                        eq(before['actual_revision']['size_bytes'], '20000', ident + '.EOF-size')
                    else:
                        eq(before['actual_revision'], None, ident + '.no-actual-revision')
                    assertions = ['V1 complete report equivalence', 'unavailable/exit1', case['reason'],
                                  case['baseline_state'], 'current verified', 'calculation absent; four integral/subset nulls']
                results.append(dict(id=ident, passed=True, assertions=assertions, report_reference=ident))
            finally:
                if not obj_path.exists() or obj_path.read_bytes() != original:
                    obj_path.write_bytes(original)
                if desc_path.read_bytes() != desc_raw:
                    desc_path.write_bytes(desc_raw)
            eq({k: x['sha256'] for k, x in files_inventory(paths + packages).items()}, original_hashes, ident + '.restored-hashes')
            value, raw = self.invoke(ident + '-restored', args, repeat_of='L-sample-1')
            self.validate_report('L', value, raw, paths, packages, f)
            eq(raw, valid_raw, ident + '.restored-valid-byte-identical')
            results[-1]['restored_valid_stdout_sha256'] = sha(raw)
        return results


